C = lambda o: json.dumps(o, ensure_ascii=False, separators=(",", ":"))


def cmd(code, *p):
    return {"code": code, "indent": 0, "parameters": list(p)}


def write_map(game, mid, cmds, pic=None):
    page_cmds = list(cmds)
    for k, name in enumerate([pic] if isinstance(pic, str) else (pic or [])):
        page_cmds.insert(0, cmd(231, k + 1, name, 0, 0, 0, 0, 100, 100, 255, 0))
    m = {"data": [0], "note": "", "events": [None, {"id": 1, "name": "EV", "x": 3, "y": 4, "pages": [
        {"conditions": {}, "list": page_cmds + [cmd(0)]}]}]}
    (game / f"data/Map{mid:03d}.json").write_text(C(m) + "\n")


def build(root: Path, dynamic=False, plugin_map=True) -> Path:
    game = fixture.build(root)
    # drop the fixture's own map: this project defines its own set
    (game / "data/Map001.json").unlink()
    infos = [None] + [{"id": i, "name": f"Map {i}", "order": i, "parentId": 0 if i != 3 else 1}
                      for i in (1, 2, 3, 4, 5, 6, 7, 8)]
    (game / "data/MapInfos.json").write_text("[\n" + ",\n".join(C(i) for i in infos) + "\n]\n")
    sysd = json.loads((game / "data/System.json").read_text())
    sysd["startMapId"] = 1
    (game / "data/System.json").write_text(C(sysd) + "\n")
    # pictures: Shared used by maps 1 and 5, OnlyFive by 5, OnlyFour by 4, OnlySeven by 7
    for n in ("Shared", "OnlyFive", "OnlyFour", "OnlySeven"):
        (game / f"img/pictures/{n}.png").write_bytes(fixture._png("m/" + n))
    first = [cmd(201, 0, 2, 0, 0, 2, 0)]
    if dynamic:
        first.append(cmd(201, 1, 9, 10, 11, 2, 0))
    write_map(game, 1, first, "Shared")
    write_map(game, 2, [cmd(201, 0, 3, 0, 0, 2, 0),
                        cmd(355, "$gamePlayer.reserveTransfer(10, 1, 1, 0, 0);")])          # script
    write_map(game, 3, [cmd(201, 0, 1, 0, 0, 2, 0), cmd(201, 0, 50, 0, 0, 2, 0)])            # 50: missing
    write_map(game, 4, [], "OnlyFour")                                                       # only from 5
    write_map(game, 5, [cmd(201, 0, 4, 0, 0, 2, 0)], ["OnlyFive", "Shared"])                             # nobody enters 5
    write_map(game, 6, [])                                                                    # from a common event
    write_map(game, 7, [], "OnlySeven")                                                      # plugin param
    write_map(game, 9, [])                                                                    # orphan file
    write_map(game, 10, [])                                                                   # via script only
    infos.append({"id": 10, "name": "Script map", "order": 10, "parentId": 0})
    (game / "data/MapInfos.json").write_text("[\n" + ",\n".join(C(i) for i in infos) + "\n]\n")
    # map 8: in MapInfos, no file
    shared = game / "data/Map005.json"
    (game / "data/CommonEvents.json").write_text(
        "[\nnull,\n" + C({"id": 1, "name": "Go", "switchId": 1, "trigger": 0,
                          "list": [cmd(201, 0, 6, 0, 0, 2, 0), cmd(0)]}) + "\n]\n")
    plug = json.loads((game / "js/plugins.js").read_text()[len("// Generated by RPG Maker.\n// Do not edit this file directly.\nvar $plugins =\n"):].rsplit("]", 1)[0] + "]")
    if plugin_map:
        plug.append({"name": "TeleHelper", "status": True, "description": "", "parameters": {"HomeMapId": "7"}})
    (game / "js/plugins.js").write_text("var $plugins =\n" + C(plug) + ";\n")
    return game


def rows_of(game, ann=None):
    assets, _ = build_asset_index(game)
    scan = mapscan.scan_maps(game, assets, ann)
    return scan, {r.id: r for r in scan.rows}


class MapScanTests(unittest.TestCase):
    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp())
        self.game = build(self.tmp / "g")
        self.scan, self.rows = rows_of(self.game)

    def tearDown(self):
        shutil.rmtree(self.tmp, ignore_errors=True)

    def st(self, i):
        return self.rows[i].status

    def test_reachability(self):
        self.assertEqual(self.st(1), "reachable")            # start map
        self.assertEqual(self.st(2), "reachable")            # 1 -> 2
        self.assertEqual(self.st(3), "reachable")            # 2 -> 3
        self.assertEqual(self.st(6), "reachable")            # common event transfer
        self.assertEqual(self.st(10), "reachable")           # reserveTransfer(10,...) from map 2
        self.assertEqual(self.st(5), "unused")               # nobody enters it
        self.assertEqual(self.st(4), "unused")               # only reached from unused map 5
        self.assertIn("only reached from unused maps (5)", self.rows[4].note)
        self.assertEqual(self.rows[5].note, "nothing transfers here")
        self.assertEqual(self.st(7), "possible")             # plugin parameter HomeMapId
        self.assertEqual(self.st(8), "missing_file")
        self.assertEqual(self.st(9), "orphan_file")          # file without MapInfos entry
        self.assertEqual(self.st(50), "broken")              # transfer to a map that does not exist

    def test_labels_and_counts(self):
        self.assertEqual(self.rows[3].label, "Map 1 / Map 3")        # parent chain
        self.assertEqual(self.rows[1].events, 1)
        self.assertEqual(self.rows[2].outbound, [3, 10])

    def test_assets_only_used_by_one_map_and_by_unused_maps(self):
        names = lambda r: {n for (_c, n, _s) in r.exclusive}
        self.assertEqual(names(self.rows[5]), {"OnlyFive"})
        self.assertEqual(names(self.rows[4]), {"OnlyFour"})
        self.assertEqual(names(self.rows[1]), set())                 # Shared is used by maps 1 and ...
        freed = {n for (_c, n, _s) in self.scan.freed_assets}
        self.assertEqual(freed, {"OnlyFive", "OnlyFour"})            # maps 4 and 5 are unused
        self.assertGreater(self.scan.freed_bytes, 0)

    def test_inbound_references_and_where_used(self):
        items = usage.from_db_refs(usage.Locator(self.game), self.rows[3].inbound)
        self.assertEqual(len(items), 1)
        self.assertIn("transfers the player here", items[0].what)
        self.assertEqual(items[0].event, "event 1 'EV' at (3, 4)")
        start = usage.from_db_refs(usage.Locator(self.game), self.rows[1].inbound)
        self.assertTrue(any("starting map" in i.what for i in start))
        script = usage.from_db_refs(usage.Locator(self.game), self.rows[10].inbound)
        self.assertIn("script transfers here", script[0].what)

    def test_keep_flag(self):
        Annotations(self.game).set_flagged("map:5", True)
        _s, rows = rows_of(self.game, Annotations(self.game))
        self.assertEqual(rows[5].status, "kept")
        self.assertEqual(rows[4].status, "unused")

    def test_variable_destination_makes_unused_possible(self):
        with tempfile.TemporaryDirectory() as t:
            game = build(Path(t) / "g", dynamic=True, plugin_map=False)
            scan, rows = rows_of(game)
            self.assertEqual(rows[5].status, "possible")
            self.assertEqual(rows[4].status, "possible")
            self.assertEqual(rows[9].status, "orphan_file")
            self.assertTrue(scan.dynamic)

    def test_csv(self):
        out = self.tmp / "maps.csv"
        mapscan.export_maps_csv(self.scan.rows, out)
        text = out.read_text(encoding="utf-8-sig")
        self.assertIn("nothing transfers here", text)
        self.assertIn("Map005.json", text)

    def test_missing_infos_and_data_folder(self):
        (self.game / "data/MapInfos.json").unlink()
        scan, rows = rows_of(self.game)
        self.assertTrue(any("MapInfos" in e for e in scan.errors))
        self.assertEqual(rows[1].status, "orphan_file" if False else rows[1].status)
        with tempfile.TemporaryDirectory() as t:
            self.assertTrue(mapscan.scan_maps(Path(t)).errors)


