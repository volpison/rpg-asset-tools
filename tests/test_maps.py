class TestStrayMapFiles(unittest.TestCase):
    def setUp(self):
        import tempfile
        self.tmp = Path(tempfile.mkdtemp())
        self.game = build(self.tmp)
        (self.game / "data/Map001 - Copy.json").write_text("{}", encoding="utf-8")
        (self.game / "data/Copy of Map001.json").write_text("{}", encoding="utf-8")
        (self.game / "data/Map001.json.bak").write_text("{}", encoding="utf-8")
        (self.game / "data/MyPluginData.json").write_text("{}", encoding="utf-8")

    def tearDown(self):
        import shutil
        shutil.rmtree(self.tmp, ignore_errors=True)

    def test_copies_and_backups_are_listed(self):
        import mapscan
        res = mapscan.scan_maps(self.game)
        stray = {r.filename for r in res.rows if r.status == mapscan.STRAY}
        self.assertTrue({"Map001 - Copy.json", "Copy of Map001.json", "Map001.json.bak"} <= stray)

    def test_real_map_not_replaced_by_a_copy(self):
        import mapscan
        res = mapscan.scan_maps(self.game)
        real = [r for r in res.rows if r.id == 1 and not r.filename]
        self.assertEqual(len(real), 1)
        self.assertEqual(real[0].file, "Map001.json")

    def test_unknown_json_is_stray_unless_a_plugin_mentions_it(self):
        import mapscan
        (self.game / "data/Leftover.json").write_text("{}", encoding="utf-8")
        (self.game / "js/plugins/Uses.js").write_text('fetch("data/MyPluginData.json");', encoding="utf-8")
        res = mapscan.scan_maps(self.game)
        names = {r.filename for r in res.rows if r.status == mapscan.STRAY}
        self.assertIn("Leftover.json", names)
        self.assertNotIn("MyPluginData.json", names)
        for std in ("Actors.json", "System.json", "MapInfos.json"):
            self.assertNotIn(std, names)

    def test_keep_flag_is_per_file(self):
        import mapscan
        res = mapscan.scan_maps(self.game)
        keys = {r.key for r in res.rows if r.filename}
        self.assertGreaterEqual(len(keys), 3)
        self.assertTrue(all(k.startswith("mapfile:") for k in keys))

    def test_move_stray_to_data_unused_and_undo(self):
        import rename_engine as re_
        n, _ = re_.move_to_unused(self.game, ["data/Map001 - Copy.json"], False, lambda *_: None, "_unused")
        self.assertEqual(n, 1)
        self.assertTrue((self.game / "data/_unused/Map001 - Copy.json").is_file())
        import mapscan
        res = mapscan.scan_maps(self.game)
        self.assertNotIn("Map001 - Copy.json", {r.filename for r in res.rows})   # subfolder not scanned
        re_.undo_last(self.game, lambda *_: None)
        self.assertTrue((self.game / "data/Map001 - Copy.json").is_file())


class TestUnusedFolderName(unittest.TestCase):
    def test_new_name_and_legacy_folders_are_both_skipped(self):
        import asset_paths
        tmp = Path(tempfile.mkdtemp())
        try:
            game = fixture.build(tmp)
            for d in ("_unused", "unused"):
                (game / f"img/pictures/{d}").mkdir()
                (game / f"img/pictures/{d}/Hidden_{d}.png").write_bytes(fixture._png(d))
            names = {n for (_c, n) in asset_paths.list_disk_assets(game)}
            self.assertNotIn("_unused/Hidden__unused", names)
            self.assertNotIn("unused/Hidden_unused", names)
            self.assertEqual(asset_paths.UNUSED_DIR_NAME, "_unused")
        finally:
            shutil.rmtree(tmp, ignore_errors=True)
